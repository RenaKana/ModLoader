import { test, expect, _electron as electron, type Page } from '@playwright/test'
import * as path from 'node:path'
import * as fs from 'node:fs'
import { pinNavigation } from './navigation'

// The UI uses the real isolated core and a tiny HTTP fixture, not real weights.
async function state(page: Page) {
  return page.evaluate(async () => {
    const connection = await (window as any).modloader.connection()
    const response = await fetch(`${connection.baseUrl}/api/state`, { headers: { Authorization: `Bearer ${connection.token}` } })
    return response.json()
  })
}

test('自定义引擎：添加编辑、模型登记、配置、真实进程对话及停止', async () => {
  test.setTimeout(150_000)
  const root = path.resolve(__dirname, '..')
  const directory = fs.mkdtempSync(path.join(root, 'work', 'ui-custom-engine-'))
  const weights = path.join(directory, 'fixture model.weights')
  fs.writeFileSync(weights, 'UI fixture only; not inference weights.')
  const application = await electron.launch({ args: [root], env: { ...process.env, MODLOADER_DATA_DIR: path.join(directory, 'data'), MODLOADER_SENSOR_AUTO_START: '0' }, timeout: 60_000 })
  const page = await application.firstWindow()
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  async function screenshot(name: string) {
    await page.evaluate(() => document.fonts.ready)
    const png = await application.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage()).toPNG().toString('base64'))
    fs.writeFileSync(path.join(directory, name), Buffer.from(png, 'base64'))
  }
  try {
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1380, 940))
    await pinNavigation(page)
    await expect(page.getByText('服务在线', { exact: true })).toBeVisible({ timeout: 60_000 })
    const nav = page.getByRole('navigation', { name: '主导航' })
    await nav.getByRole('button', { name: '运行环境', exact: true }).click()
    const card = page.locator('.runtime-platform[data-platform="windows"] [data-backend-id="custom"]')
    await expect(card.getByRole('button', { name: '添加引擎', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: '导入运行环境', exact: true }).click()
    await page.getByRole('dialog', { name: '导入已有运行环境', exact: true }).getByRole('combobox', { name: '运行后端', exact: true }).selectOption('custom')
    let modal = page.getByRole('dialog', { name: '添加自定义引擎', exact: true })
    await modal.getByRole('textbox', { name: '引擎名称', exact: true }).fill('自定义测试服务')
    await modal.getByRole('textbox', { name: /^启动程序/ }).fill(path.join(root, '.venv', 'Scripts', 'python.exe'))
    const args = [path.join(root, 'tests', 'fixtures', 'custom_engine_server.py'), '--model', '{model_path}', '--host', '{host}', '--port', '{port}', '--context-length', '{context_length}'].join('\n')
    await modal.getByRole('textbox', { name: /^启动参数模板/ }).fill('--model\n{model_path}')
    await modal.getByRole('button', { name: '添加引擎', exact: true }).click()
    await expect(modal.getByRole('alert')).toContainText('port')
    await modal.getByRole('textbox', { name: /^启动参数模板/ }).fill(args)
    await screenshot('custom-template.png')
    await modal.getByRole('button', { name: '服务与环境选项', exact: true }).click()
    await modal.getByRole('textbox', { name: /^工作目录/ }).fill(directory)
    await modal.getByRole('checkbox', { name: 'Top K', exact: true }).check()
    await modal.getByRole('checkbox', { name: /^支持流式用量统计/ }).scrollIntoViewIfNeeded()
    await screenshot('custom-options.png')
    await modal.getByRole('button', { name: '添加引擎', exact: true }).click()
    await expect(modal).toBeHidden()
    let snapshot = await state(page)
    const runtime = snapshot.runtimes.find((item: any) => item.backend === 'custom')
    expect(runtime.metadata.custom.args).toEqual(args.split('\n'))
    expect(snapshot.instances).toEqual([])
    expect(snapshot.installations).toEqual([])
    const row = page.locator(`[data-runtime-id="${runtime.id}"]`)
    await row.getByRole('button', { name: '编辑模板', exact: true }).click()
    modal = page.getByRole('dialog', { name: '编辑自定义引擎', exact: true })
    await expect(modal.getByRole('textbox', { name: /^启动参数模板/ })).toHaveValue(args)
    await modal.getByRole('textbox', { name: '引擎名称', exact: true }).fill('本机测试引擎')
    await modal.getByRole('button', { name: '保存模板', exact: true }).click()
    await expect(modal).toBeHidden()

    await nav.getByRole('button', { name: '模型库', exact: true }).click()
    await page.getByRole('button', { name: '导入模型', exact: true }).click()
    modal = page.getByRole('dialog', { name: '导入模型文件', exact: true })
    await modal.getByRole('checkbox', { name: '按自定义模型路径登记', exact: true }).check()
    await modal.getByRole('textbox', { name: /^模型路径/ }).fill(weights)
    await modal.getByRole('textbox', { name: /^显示名称/ }).fill('自定义权重测试')
    await modal.getByRole('button', { name: '导入', exact: true }).click()
    await expect(modal).toBeHidden()
    await page.getByRole('button', { name: '新建配置', exact: true }).first().click()
    modal = page.getByRole('dialog', { name: '新建加载配置', exact: true })
    await expect(modal.getByRole('combobox', { name: '运行后端', exact: true })).toHaveValue('custom')
    await modal.getByRole('textbox', { name: '配置名称', exact: true }).fill('测试启动配置')
    await modal.getByRole('textbox', { name: 'API 模型名称', exact: true }).fill('custom-ui-test')
    await modal.getByRole('spinbutton', { name: /^上下文长度/ }).fill('4096')
    await expect(modal.getByText('MTP 推测加速', { exact: true })).toHaveCount(0)
    await expect(modal.getByText('导入配置原始数据', { exact: true })).toHaveCount(0)
    await screenshot('custom-profile.png')
    await modal.getByRole('tab', { name: '生成默认值', exact: true }).click()
    await modal.getByRole('spinbutton', { name: 'Top K', exact: true }).fill('40')
    await expect(modal.getByRole('spinbutton', { name: '重复惩罚', exact: true })).toHaveCount(0)
    await modal.getByRole('button', { name: '保存配置', exact: true }).click()
    await expect(modal).toBeHidden()
    const profile = page.locator('.profile-card').filter({ hasText: '测试启动配置' })
    await profile.getByRole('button', { name: '启动参数', exact: true }).click()
    modal = page.getByRole('dialog', { name: '编辑加载配置', exact: true })
    await expect(modal.getByRole('tab', { name: '启动参数', exact: true })).toHaveAttribute('aria-selected', 'true')
    await expect(modal.getByRole('textbox', { name: '启动参数', exact: true })).toHaveValue(/4096/)
    await expect(modal.getByRole('textbox', { name: '启动参数', exact: true })).toHaveValue(/fixture model.weights/)
    await modal.getByRole('button', { name: '取消', exact: true }).click()
    await profile.getByRole('button', { name: '加载模型', exact: true }).click()
    await expect(profile.getByText('运行中', { exact: true })).toBeVisible({ timeout: 30_000 })
    snapshot = await state(page)
    expect(snapshot.profiles[0].runtime_id).toBe(runtime.id)
    expect(snapshot.instances[0].pid).toBeGreaterThan(0)
    await profile.getByRole('button', { name: '日志', exact: true }).click()
    await expect(page.getByRole('dialog')).toContainText('模型已就绪')
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).first().click()
    await profile.getByRole('button', { name: '测试对话', exact: true }).click()
    await page.getByRole('textbox', { name: '对话消息', exact: true }).fill('测试自定义引擎')
    await page.getByRole('button', { name: '发送消息', exact: true }).click()
    await expect(page.locator('.chat-message.assistant .message-markdown')).toContainText('自定义引擎接线成功。', { timeout: 20_000 })
    await expect(page.getByRole('button', { name: '停止生成', exact: true })).toHaveCount(0)
    await screenshot('custom-chat.png')
    await nav.getByRole('button', { name: '运行环境', exact: true }).click()
    await expect(row.getByRole('button', { name: '编辑模板', exact: true })).toBeDisabled()
    await page.locator('.instance-table-row').getByRole('button', { name: '停止', exact: true }).click()
    await expect(row.getByRole('button', { name: '编辑模板', exact: true })).toBeEnabled()
    snapshot = await state(page)
    expect(snapshot.instances[0].state).toBe('stopped')
    expect(snapshot.downloads).toEqual([])
    expect(snapshot.installations).toEqual([])
    expect(fs.readFileSync(weights, 'utf8')).toBe('UI fixture only; not inference weights.')
    const modelDirectory = path.join(directory, 'opaque-model')
    fs.mkdirSync(modelDirectory)
    await nav.getByRole('button', { name: '模型库', exact: true }).click()
    await page.getByRole('button', { name: '导入模型', exact: true }).click()
    modal = page.getByRole('dialog', { name: '导入模型文件', exact: true })
    await modal.getByRole('checkbox', { name: '按自定义模型路径登记', exact: true }).check()
    await modal.getByRole('combobox', { name: '路径类型', exact: true }).selectOption('directory')
    await modal.getByRole('textbox', { name: /^模型路径/ }).fill(modelDirectory)
    await modal.getByRole('textbox', { name: /^显示名称/ }).fill('自定义模型目录')
    await modal.getByRole('button', { name: '导入', exact: true }).click()
    await expect(modal).toBeHidden()
    await expect(page.locator('.workspace-summary')).toContainText('1 项未统计')
    await page.getByRole('button', { name: /自定义模型目录.*CUSTOM/ }).click()
    await expect(page.locator('.model-facts')).toContainText('未统计')
    await screenshot('custom-directory.png')
    expect(errors).toEqual([])
    console.log(`Custom engine UI evidence: ${directory}`)
  } finally { await application.close() }
})
